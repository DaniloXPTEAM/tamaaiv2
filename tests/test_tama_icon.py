"""The launcher icon: the turtle survived the pipeline.

These read the files the app actually ships. They are not a pixel-diff test (there is no
reference bitmap to compare against, and inventing one would only test the bitmap); they assert
the things that silently broke before: a vector that lost its fill type, a notification icon
pointing at a drawable that no longer exists, and app code still asking for upstream's icon.
"""

from __future__ import annotations

import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "android/src/android/app/src/main/res"
ANDROID = "http://schemas.android.com/apk/res/android"


def test_the_launcher_foreground_is_the_turtle_and_keeps_its_holes():
    fg = RES / "drawable/ic_launcher_foreground_tama.xml"
    assert fg.exists(), "the TAMA foreground must be generated by scripts/gen-android-icons.py"
    root = ET.parse(fg).getroot()
    paths = root.findall("path")
    assert len(paths) == 1, "one path, so the mark cannot drift apart into pieces"
    path = paths[0]
    # The A, the eye and the carapace seam are holes. Without evenodd they fill in and the icon
    # becomes a solid blob, which is exactly what a fill-type regression looks like.
    assert path.get(f"{{{ANDROID}}}fillType") == "evenodd"
    d = path.get(f"{{{ANDROID}}}pathData")
    assert d.count("M") >= 4, "shell, head, legs and stubs are separate contours"
    assert d.count("L") > 200, "the traced geometry, not a placeholder"
    # The gradient is the app's own two blues, so the icon matches the rest of the brand.
    assert "#FF015CFB" in fg.read_text() and "#FF0186FB" in fg.read_text()


def test_the_adaptive_icon_points_at_the_turtle():
    adaptive = (RES / "mipmap-anydpi-v26/ic_launcher.xml").read_text()
    assert "@drawable/ic_launcher_foreground_tama" in adaptive
    assert "ic_launcher_foreground_nm" not in adaptive
    assert "@drawable/ic_launcher_monochrome" in adaptive, "themed icons need a mask"


def test_the_dark_skin_is_white_and_also_the_turtle():
    dark = (RES / "drawable/ic_launcher_foreground_tama_dark.xml").read_text()
    assert "#FFFFFFFF" in dark
    assert (RES / "mipmap-anydpi-v26/ic_launcher_classic_dark.xml").read_text().count(
        "ic_launcher_foreground_tama_dark"
    ) == 1


def test_the_notification_icon_is_24dp_and_drops_the_seam():
    stat = RES / "drawable/ic_stat_tama.xml"
    assert stat.exists()
    root = ET.parse(stat).getroot()
    assert root.get(f"{{{ANDROID}}}viewportWidth") == "24"
    path = root.find("path")
    assert path.get(f"{{{ANDROID}}}fillType") == "evenodd"
    # Four contours: shell, head and the two A strokes. The seam would be a fifth and is under
    # half a pixel here, so it must be absent rather than a grey halo.
    assert path.get(f"{{{ANDROID}}}pathData").count("M") == 4


def test_no_app_code_asks_for_upstreams_notification_icon():
    offenders = []
    for f in (ROOT / "android/src/android/app/src/main/java").rglob("*.kt"):
        text = f.read_text(encoding="utf-8")
        if "R.drawable.ic_stat_nanomuse" in text:
            offenders.append(str(f.relative_to(ROOT)))
    assert offenders == [], f"notifications still draw the nanoMuse mark: {offenders}"


def test_the_brand_svg_is_the_same_shape_as_the_geometry():
    svg = ROOT / "assets/brand/tama-mark.svg"
    assert svg.exists(), "tools/icon/emit.py writes this file"
    text = svg.read_text()
    d = re.search(r'\sd="([^"]+)"', text).group(1)
    # The generator reads exactly this, so a truncated path has to fail here and not in a build.
    assert d.startswith("M") and d.endswith("Z")
    assert d.count("L") > 200
    nums = [float(v) for v in re.findall(r"-?\d+\.?\d*", d)]
    assert nums and min(nums) >= 0 and max(nums) <= 100, "the design box is 0..100"
